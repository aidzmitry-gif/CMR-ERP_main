/**
 * Скрипты звонка по контексту (порт из sales-call-popup.html).
 *
 * Единое окно звонка <CallWindow> одинаково по принципам для лида и сделки,
 * но СКРИПТ разный: у лида — приём/квалификация нового интереса, у сделки —
 * сопровождение по активной воронке. Это намеренно ДАННЫЕ, а не разметка —
 * чтобы РОП/продавец правил пункты под реальные функции без правки React.
 *
 * Чекбоксы — состояние в рантайме (CallWindow держит Set отмеченных по `id`).
 * `tip: true` — пункт-подсказка (💡 допродажа и т.п.), визуально выделяется.
 */
export interface ScriptItem {
  /** Стабильный ключ пункта (для отметки галочки). */
  id: string;
  text: string;
  /** Предотмечен по умолчанию (напр. «поздороваться»). */
  done?: boolean;
  /** Пункт-подсказка (допродажа, лайфхак) — выделяется акцентом. */
  tip?: boolean;
}

export interface ScriptSection {
  /** Номер шага (1..N) или значок. */
  n: string;
  title: string;
  items: ScriptItem[];
}

export type CallScript = ScriptSection[];

