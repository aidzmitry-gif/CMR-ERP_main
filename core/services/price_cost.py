"""Контракт шлюза цены/себестоимости из 1С — фасад ядра к учётным цене продажи и себестоимости.

Решение оператора (память ``cost-price-from-1c-decision``): цена продавца и себестоимость
берутся из 1С (справочник цен продажи + учётная себестоимость), а НЕ считаются наценкой от
landed. Данные — СПРАВОЧНЫЕ: золотая запись справочника/MDM с провенансом ``source=1С``, её
материализуют полосы Справочники + ``integrations`` (pull из 1С). Продажи только ПОТРЕБЛЯЮТ
через этот фасад — своей «правды» не заводят, в 1С напрямую не ходят (правило границ §2.4).

Реализацию регистрируют в фасаде при загрузке: ``core.services.price_cost = <impl>`` —
reference-backed (из справочника) либо dev-фикстура. Ядро держит лишь этот протокол: маржа
сделки, дефолт цены в КП и дефолты конструктора плана читают через ``core.services.price_cost``,
не импортируя ``integrations``. Пока источник не подключён — поле ``None``, потребители
деградируют ЧЕСТНО: нет данных, а НЕ ноль (PLATFORM #1 — нельзя показывать фейковые деньги;
пустое ≠ бесплатно, скрыло бы дыру в марже).

Остатки — НЕ здесь (транзакционные, свой ``StockGateway``: 1С=истина, живое чтение).
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from typing import Literal, Protocol

from sqlalchemy.ext.asyncio import AsyncSession

# Провенанс значения — для честной пометки в UI («из 1С» / «демо») и приоритета источников
# в марже (onec бьёт landed). ``landed`` — себес из закупок (фасад landed_cost) как фолбэк/сверка.
Source = Literal["onec", "landed", "demo"]


@dataclass(frozen=True)
class ItemPriceCost:
    """Цена продажи и себестоимость номенклатуры из учётной системы (на код SKU).

    ``cost_byn``/``price_byn`` — ``None`` при отсутствии данных (НЕ 0: пустое ≠ бесплатно —
    ноль замаскировал бы дыру в себестоимости/цене). ``source`` — провенанс для UI-пометки.
    ``price_type`` — тип цены 1С (напр. «оптовая»); конкретный регистр выбирается в офисе на
    реальной базе, поэтому здесь необязателен. ``as_of`` — дата актуальности записи (когда
    цена/себес зафиксированы), для честной пометки давности данных.
    """

    cost_byn: float | None = None
    price_byn: float | None = None
    currency: str = "BYN"
    price_type: str | None = None
    as_of: date | None = None
    source: Source | None = None


class PriceCostGateway(Protocol):
    """Чтение цены продажи и себестоимости номенклатуры из учётной системы (по коду SKU).

    Реализация — reference-backed (золотая запись справочника, наполняемая из 1С через
    ``integrations``) либо dev-фикстура. Возврат — словарь ТОЛЬКО по найденным кодам:
    отсутствующий в словаре код = нет данных по нему (потребитель деградирует по нему честно).
    Пустой ввод → пустой словарь. Форма гибкая под 1С (тип цены + дата актуальности),
    но не привязана к её схеме — при подключении живой 1С меняется только реализация за фасадом.
    """

    async def get_item_price_cost(
        self, session: AsyncSession, sku_codes: list[str]
    ) -> dict[str, ItemPriceCost]: ...
